using System.Collections.Concurrent;
using System.Security.Cryptography;
using Handlers.DataHandling;

namespace CRT.Server.Handlers.Submissions
{
    // ###########################################################################################
    // THE SHA-256 OF EACH PUBLISHED FILE A SUBMISSION ALSO CARRIES, so the maintainer app can tell an
    // unchanged file from a replaced one (fixed 2026-09-23).
    //
    // *** WHY THIS EXISTS: WITHOUT IT, EVERY FILE ON BOTH SIDES READS AS "REPLACED". *** A
    // submission names every file the board references, with a hash, because the manifest
    // describes the whole intended state. The maintainer app pairs those against the published
    // list, and ReviewImageComparison.Plan drops a pair only when it is told the published hash
    // and it matches. Nothing sent that hash, so a submission that changed one component's short
    // description was shown to the maintainer as "1178 images to compare" - all of them identical.
    //
    // *** THE FILES ARE HASHED HERE, NOT READ OUT OF dataChecksums.json, DELIBERATELY. *** That
    // manifest holds the same hash for every file, but nothing in this service writes it - it is
    // regenerated by hand on the old PHP path - so it goes stale the moment this service
    // publishes anything. A stale hash that happens to equal the submitted one HIDES a real
    // change, and hiding a change is the one direction this screen must never be wrong in.
    // Hashing the bytes on disk is always true.
    //
    // *** EVERY SUBMITTED PATH THAT EXISTS IS HASHED, not only the ones the published board cites
    // (security review, 2026-09-25). *** This used to hash just the paths on BOTH lists, so a file
    // the submission would OVERWRITE but the old board never cited was reported to the maintainer as
    // "added" - exactly backwards for the one case that matters, a submission writing over a file
    // it has no business touching. What is on disk is the truth; the published board's list is not.
    //
    // THE COST IS SMALL AND MOSTLY PAID ONCE. The whole C64 250407 folder is 76 MB across ~1,100
    // files, well under a second, and the cache below keys on length plus last-write time so a
    // maintainer refreshing the same submission pays nothing. The same hash, taken synchronously, is
    // what PublishedTreeProbe answers "is this file published unchanged?" with.
    //
    // CONTAINMENT IS THE SAME RULE AS EVERY OTHER PATH INTO THE TREE. The paths come from the
    // published workbook, which this service wrote, but they are still resolved through
    // SubmissionPathRules rather than combined directly - a workbook published by the old PHP
    // path is not something this code should trust to be well-formed.
    // ###########################################################################################
    public static class PublishedFileHashes
    {
        private sealed record CachedHash(long Length, long WriteTimeUtcTicks, string Sha256);

        // Keyed on the RESOLVED full path, so two data trees on one machine (BETA and production)
        // cannot hand each other a hash.
        private static readonly ConcurrentDictionary<string, CachedHash> Cache =
            new(StringComparer.Ordinal);

        // ###########################################################################################
        // Path -> lowercase hex SHA-256, for every path that resolves safely and exists.
        //
        // A path that does not resolve or is not on disk is simply absent from the result, never
        // an error: the maintainer app then treats that file as replaced, which is the safe direction
        // to be wrong in (shown to a maintainer rather than hidden from one).
        //
        // Lowercase hex, because that is what the client sends in the manifest, what
        // dataChecksums.json holds, and what ReviewImageComparison compares with an ORDINAL
        // equality - a hash in the other case would compare unequal and read as a replacement.
        // ###########################################################################################
        public static async Task<IReadOnlyDictionary<string, string>> ComputeAsync(
            string? dataTreeRoot,
            IReadOnlyList<string> paths,
            CancellationToken cancellationToken)
        {
            var hashes = new Dictionary<string, string>(StringComparer.Ordinal);

            if (string.IsNullOrWhiteSpace(dataTreeRoot))
                return hashes;

            foreach (string path in paths)
            {
                if (!SubmissionPathRules.TryResolve(dataTreeRoot, path, out string resolved, out _))
                    continue;

                var info = new FileInfo(resolved);

                if (!info.Exists)
                    continue;

                hashes[path] = await PublishedFileHashes.HashAsync(info, cancellationToken)
                    .ConfigureAwait(false);
            }

            return hashes;
        }

        // ###########################################################################################
        // The hash of ONE published file, synchronously, or null when the path does not resolve
        // inside the tree or nothing is there. For PublishedTreeView, whose questions are asked
        // from pure rules that cannot await.
        //
        // *** A SYNCHRONOUS READ, NOT AN ASYNC ONE WAITED ON (code review, 2026-09-25). *** This
        // used to call HashAsync(...).GetAwaiter().GetResult(), parking a request thread while the
        // async read completed on another - per shared or foreign file, during create, review,
        // amend and both plans. Under load that starves the thread pool and every other request
        // (sign-in, CRT's status checks at launch) queues behind it. Hashing with a plain blocking
        // stream uses the one thread it already has. Same cache, same answer.
        // ###########################################################################################
        public static string? TryHash(string? dataTreeRoot, string relativePath)
        {
            if (string.IsNullOrWhiteSpace(dataTreeRoot))
                return null;

            if (!SubmissionPathRules.TryResolve(dataTreeRoot, relativePath, out string resolved, out _))
                return null;

            var info = new FileInfo(resolved);

            if (!info.Exists)
                return null;

            try
            {
                return PublishedFileHashes.Hash(info);
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                // Unreadable is not "absent unchanged" - the caller's rule then refuses, which is
                // the safe direction.
                return null;
            }
        }

        // ###########################################################################################
        // The cache check and the hash itself.
        //
        // Length AND last-write time, because either alone is fooled by an ordinary publish: a
        // replaced scan is very often the same length, and a file rewritten within the timestamp's
        // resolution keeps its time. Both changing on a rewrite that keeps both is rare enough to
        // accept; the alternative is hashing 76 MB on every refresh.
        // ###########################################################################################
        private static async Task<string> HashAsync(FileInfo info, CancellationToken cancellationToken)
        {
            long writeTicks = info.LastWriteTimeUtc.Ticks;

            if (PublishedFileHashes.TryCached(info, writeTicks, out string known))
                return known;

            await using var stream = new FileStream(
                info.FullName,
                FileMode.Open,
                FileAccess.Read,
                FileShare.Read,
                bufferSize: 1 << 16,
                useAsync: true);

            byte[] hash = await SHA256.HashDataAsync(stream, cancellationToken).ConfigureAwait(false);

            return PublishedFileHashes.Remember(info, writeTicks, hash);
        }

        // The same, on the calling thread - for TryHash.
        private static string Hash(FileInfo info)
        {
            long writeTicks = info.LastWriteTimeUtc.Ticks;

            if (PublishedFileHashes.TryCached(info, writeTicks, out string known))
                return known;

            using var stream = new FileStream(
                info.FullName,
                FileMode.Open,
                FileAccess.Read,
                FileShare.Read,
                bufferSize: 1 << 16,
                useAsync: false);

            return PublishedFileHashes.Remember(info, writeTicks, SHA256.HashData(stream));
        }

        private static bool TryCached(FileInfo info, long writeTicks, out string hash)
        {
            if (PublishedFileHashes.Cache.TryGetValue(info.FullName, out CachedHash? cached)
                && cached.Length == info.Length
                && cached.WriteTimeUtcTicks == writeTicks)
            {
                hash = cached.Sha256;
                return true;
            }

            hash = string.Empty;
            return false;
        }

        private static string Remember(FileInfo info, long writeTicks, byte[] hash)
        {
            string hex = Convert.ToHexStringLower(hash);

            PublishedFileHashes.Cache[info.FullName] = new CachedHash(info.Length, writeTicks, hex);

            return hex;
        }
    }
}
